#!/usr/bin/env bash
set -euo pipefail

USER_HOME="${USER_HOME:-/home/xmyf}"
SLIME_HOME="${SLIME_HOME:-${USER_HOME}/slime}"
LIVEWEB_ARENA_DIR="${LIVEWEB_ARENA_DIR:-${USER_HOME}/liveweb-arena}"
RUN_ROOT="${RUN_ROOT:-${USER_HOME}/slime_runs}"

MODEL_LABEL="${MODEL_LABEL:-glm5_openrouter}"
MODEL_ID="${MODEL_ID:-z-ai/glm-5}"
OPENROUTER_API_KEY="${OPENROUTER_API_KEY:-}"
OPENROUTER_BASE_URL="${OPENROUTER_BASE_URL:-https://openrouter.ai/api/v1}"

NUM_EVAL_RUNS="${NUM_EVAL_RUNS:-250}"
NUM_TASKS_PER_RUN="${NUM_TASKS_PER_RUN:-4}"
MAX_STEPS="${MAX_STEPS:-30}"
TEMPERATURE="${TEMPERATURE:-0.0}"
TIMEOUT_SECONDS="${TIMEOUT_SECONDS:-1800}"
START_SEED="${START_SEED:-2001}"
LIVEWEB_MAX_COMPLETION_TOKENS="${LIVEWEB_MAX_COMPLETION_TOKENS:-1024}"
LIVEWEB_IGNORE_HTTPS_ERRORS="${LIVEWEB_IGNORE_HTTPS_ERRORS:-1}"
LIVEWEB_PREFETCH_TIMEOUT_NAV="${LIVEWEB_PREFETCH_TIMEOUT_NAV:-12}"
LIVEWEB_PREFETCH_TIMEOUT_DATA="${LIVEWEB_PREFETCH_TIMEOUT_DATA:-25}"
LIVEWEB_CACHE_ALLOW_STALE="${LIVEWEB_CACHE_ALLOW_STALE:-1}"
LIVEWEB_CACHE_STALE_MAX_AGE="${LIVEWEB_CACHE_STALE_MAX_AGE:-86400}"
LIVEWEB_MAX_CACHE_FETCHES="${LIVEWEB_MAX_CACHE_FETCHES:-4}"
LIVEWEB_CACHE_DOMAIN_LIMIT_DEFAULT="${LIVEWEB_CACHE_DOMAIN_LIMIT_DEFAULT:-2}"
LIVEWEB_CACHE_DOMAIN_LIMIT_COINGECKO="${LIVEWEB_CACHE_DOMAIN_LIMIT_COINGECKO:-1}"
LIVEWEB_CACHE_DOMAIN_LIMIT_STOOQ="${LIVEWEB_CACHE_DOMAIN_LIMIT_STOOQ:-1}"
LIVEWEB_CACHE_DOMAIN_LIMIT_NEWS_YCOMBINATOR="${LIVEWEB_CACHE_DOMAIN_LIMIT_NEWS_YCOMBINATOR:-2}"
LIVEWEB_CACHE_DOMAIN_LIMIT_TAOSTATS="${LIVEWEB_CACHE_DOMAIN_LIMIT_TAOSTATS:-2}"
MAX_BROWSER_SESSIONS="${MAX_BROWSER_SESSIONS:-12}"
MAX_LLM_REQUESTS="${MAX_LLM_REQUESTS:-6}"
CACHE_PROFILE="${CACHE_PROFILE:-hot}"
PREWARM_BROWSERS="${PREWARM_BROWSERS:-0}"
LIVEWEB_CACHE_PREFETCH_INTERVAL="${LIVEWEB_CACHE_PREFETCH_INTERVAL:-}"
TEMPLATES_JSON="${TEMPLATES_JSON:-}"

TIMESTAMP="${TIMESTAMP:-$(date +%Y%m%d_%H%M%S)}"
OUT_ROOT="${OUT_ROOT:-${RUN_ROOT}/liveweb_${MODEL_LABEL}_trajectory_collection_${TIMESTAMP}}"
OUT_DIR="${OUT_ROOT}/${MODEL_LABEL}"
PERSISTENT_CACHE_ROOT="${PERSISTENT_CACHE_ROOT:-${LIVEWEB_ARENA_DIR}/.cache/persistent}"
CACHE_ROOT="${CACHE_ROOT:-${PERSISTENT_CACHE_ROOT}/${MODEL_LABEL}}"
LOG_DIR="${OUT_ROOT}/logs"

if [[ -z "${OPENROUTER_API_KEY}" ]]; then
  echo "OPENROUTER_API_KEY is required" >&2
  exit 1
fi

mkdir -p "${OUT_DIR}" "${CACHE_ROOT}" "${LOG_DIR}"

source "${USER_HOME}/.venvs/slime/bin/activate"

cd "${LIVEWEB_ARENA_DIR}"
export LIVEWEB_MAX_COMPLETION_TOKENS
export LIVEWEB_IGNORE_HTTPS_ERRORS
export LIVEWEB_CACHE_DIR="${CACHE_ROOT}/shared"
export LIVEWEB_PREFETCH_TIMEOUT_NAV
export LIVEWEB_PREFETCH_TIMEOUT_DATA
export LIVEWEB_CACHE_ALLOW_STALE
export LIVEWEB_CACHE_STALE_MAX_AGE
export LIVEWEB_MAX_CACHE_FETCHES
export LIVEWEB_CACHE_DOMAIN_LIMIT_DEFAULT
export LIVEWEB_CACHE_DOMAIN_LIMIT_COINGECKO
export LIVEWEB_CACHE_DOMAIN_LIMIT_STOOQ
export LIVEWEB_CACHE_DOMAIN_LIMIT_NEWS_YCOMBINATOR
export LIVEWEB_CACHE_DOMAIN_LIMIT_TAOSTATS
if [[ -z "${LIVEWEB_CACHE_PREFETCH_INTERVAL}" ]]; then
  if [[ "${CACHE_PROFILE}" == "hot" ]]; then
    export LIVEWEB_CACHE_PREFETCH_INTERVAL="0.1"
  else
    export LIVEWEB_CACHE_PREFETCH_INTERVAL="0.5"
  fi
else
  export LIVEWEB_CACHE_PREFETCH_INTERVAL
fi
mkdir -p "${LIVEWEB_CACHE_DIR}"

python3 "${SLIME_HOME}/scripts/liveweb_arena_dynamic_batch_runner.py" \
  --liveweb-arena-dir "${LIVEWEB_ARENA_DIR}" \
  --result-dir "${OUT_DIR}" \
  --progress-log "${LOG_DIR}/progress.log" \
  --summary-path "${OUT_ROOT}/summary.json" \
  --base-url "${OPENROUTER_BASE_URL}" \
  --api-key "${OPENROUTER_API_KEY}" \
  --model-name "${MODEL_ID}" \
  --num-runs "${NUM_EVAL_RUNS}" \
  --start-seed "${START_SEED}" \
  --num-tasks "${NUM_TASKS_PER_RUN}" \
  --max-steps "${MAX_STEPS}" \
  --timeout "${TIMEOUT_SECONDS}" \
  --temperature "${TEMPERATURE}" \
  --cache-dir "${LIVEWEB_CACHE_DIR}" \
  --mode collect \
  --cache-profile "${CACHE_PROFILE}" \
  $( [[ -n "${TEMPLATES_JSON}" ]] && printf -- '--templates-json %q ' "${TEMPLATES_JSON}" ) \
  --route-policy sticky_steal \
  --max-browser-sessions "${MAX_BROWSER_SESSIONS}" \
  --max-llm-requests "${MAX_LLM_REQUESTS}" \
  $( [[ "${PREWARM_BROWSERS}" == "1" ]] && printf '%s' '--prewarm-browsers' )
